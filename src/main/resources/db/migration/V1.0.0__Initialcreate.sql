-- Vorlagenverwaltung (Querschnittsdienst Dokumentenerstellung, QD10)
-- Nur DDL. Zeitpunkte als TIMESTAMP WITH TIME ZONE (java.time.Instant). Sequenzen mit INCREMENT BY 50 passend zu allocationSize = 50.

CREATE SEQUENCE SEQ_KATEGORIE START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE SEQ_VORLAGE START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE SEQ_VORLAGE_VERSION START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE SEQ_INHALT START WITH 1 INCREMENT BY 50;

-- Kategorie (≙ Fachsystem)
CREATE TABLE KATEGORIE (
    ID             NUMBER(19)                  NOT NULL,
    NAME           VARCHAR2(30 CHAR)           NOT NULL,
    BESCHREIBUNG   VARCHAR2(2000 CHAR),
    ERSTELLT_TIME  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ERSTELLT_VON   VARCHAR2(255 CHAR)          NOT NULL,
    GEAENDERT_TIME TIMESTAMP(6) WITH TIME ZONE,
    GEAENDERT_VON  VARCHAR2(255 CHAR),
    REVISION       NUMBER(19) DEFAULT 0        NOT NULL,
    CONSTRAINT KATEGORIE_PK PRIMARY KEY (ID),
    CONSTRAINT KATEGORIE_UK_NAME UNIQUE (NAME)
);

-- Inhalte (ODT, PDF, XSD): Metadaten und Binärdaten getrennt, damit beim Laden von Versionen keine BLOBs gelesen werden
CREATE TABLE INHALT (
    ID            NUMBER(19)                  NOT NULL,
    SHA256        CHAR(64 CHAR)               NOT NULL,
    FORMAT        VARCHAR2(10 CHAR)           NOT NULL,
    GROESSE       NUMBER(19)                  NOT NULL,
    ERSTELLT_TIME TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT INHALT_PK PRIMARY KEY (ID),
    CONSTRAINT INHALT_UK_SHA UNIQUE (SHA256, FORMAT),
    CONSTRAINT INHALT_CK_FORMAT CHECK (FORMAT IN ('ODT', 'PDF', 'XSD'))
);

CREATE TABLE INHALT_DATEN (
    INHALT_ID NUMBER(19) NOT NULL,
    DATEN     BLOB       NOT NULL,
    CONSTRAINT INHALT_DATEN_PK PRIMARY KEY (INHALT_ID),
    CONSTRAINT INHALT_DATEN_FK_INHALT FOREIGN KEY (INHALT_ID) REFERENCES INHALT (ID)
);

-- Vorlage (Formular, Baustein, Merkblatt)
CREATE TABLE VORLAGE (
    ID                       NUMBER(19)                  NOT NULL,
    KATEGORIE_ID             NUMBER(19)                  NOT NULL,
    NAME                     VARCHAR2(100 CHAR)          NOT NULL,
    TYP                      VARCHAR2(20 CHAR)           NOT NULL,
    BEZEICHNUNG              VARCHAR2(255 CHAR)          NOT NULL,
    BESCHREIBUNG             VARCHAR2(2000 CHAR),
    VEROEFFENTLICHT_AB_TIME  TIMESTAMP(6) WITH TIME ZONE,
    VEROEFFENTLICHT_BIS_TIME TIMESTAMP(6) WITH TIME ZONE,
    ERSTELLT_TIME            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ERSTELLT_VON             VARCHAR2(255 CHAR)          NOT NULL,
    GEAENDERT_TIME           TIMESTAMP(6) WITH TIME ZONE,
    GEAENDERT_VON            VARCHAR2(255 CHAR),
    REVISION                 NUMBER(19) DEFAULT 0        NOT NULL,
    CONSTRAINT VORLAGE_PK PRIMARY KEY (ID),
    CONSTRAINT VORLAGE_UK_NAME UNIQUE (KATEGORIE_ID, NAME),
    CONSTRAINT VORLAGE_FK_KATEGORIE FOREIGN KEY (KATEGORIE_ID) REFERENCES KATEGORIE (ID),
    CONSTRAINT VORLAGE_CK_TYP CHECK (TYP IN ('FORMULAR', 'BAUSTEIN', 'MERKBLATT')),
    CONSTRAINT VORLAGE_CK_ZEITRAUM CHECK (VEROEFFENTLICHT_AB_TIME IS NULL OR VEROEFFENTLICHT_BIS_TIME IS NULL
        OR VEROEFFENTLICHT_BIS_TIME > VEROEFFENTLICHT_AB_TIME)
);

CREATE TABLE VORLAGE_TAG (
    VORLAGE_ID NUMBER(19)         NOT NULL,
    TAG        VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT VORLAGE_TAG_PK PRIMARY KEY (VORLAGE_ID, TAG),
    CONSTRAINT VORLAGE_TAG_FK_VORLAGE FOREIGN KEY (VORLAGE_ID) REFERENCES VORLAGE (ID)
);

CREATE INDEX VORLAGE_TAG_IX_TAG ON VORLAGE_TAG (TAG);

-- Version einer Vorlage
CREATE TABLE VORLAGE_VERSION (
    ID                       NUMBER(19)                  NOT NULL,
    VORLAGE_ID               NUMBER(19)                  NOT NULL,
    HAUPT                    NUMBER(5)                   NOT NULL,
    NEBEN                    NUMBER(5)                   NOT NULL,
    STATUS                   VARCHAR2(20 CHAR)           NOT NULL,
    VEROEFFENTLICHT_AB_TIME  TIMESTAMP(6) WITH TIME ZONE,
    VEROEFFENTLICHT_BIS_TIME TIMESTAMP(6) WITH TIME ZONE,
    KOMMENTAR                VARCHAR2(2000 CHAR),
    INHALT_ID                NUMBER(19)                  NOT NULL,
    SCHEMA_ID                NUMBER(19),
    ERSTELLT_TIME            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ERSTELLT_VON             VARCHAR2(255 CHAR)          NOT NULL,
    GEAENDERT_TIME           TIMESTAMP(6) WITH TIME ZONE,
    GEAENDERT_VON            VARCHAR2(255 CHAR),
    CONSTRAINT VORLAGE_VERSION_PK PRIMARY KEY (ID),
    CONSTRAINT VORLAGE_VERSION_UK_NUMMER UNIQUE (VORLAGE_ID, HAUPT, NEBEN),
    CONSTRAINT VORLAGE_VERSION_FK_VORLAGE FOREIGN KEY (VORLAGE_ID) REFERENCES VORLAGE (ID),
    CONSTRAINT VORLAGE_VERSION_FK_INHALT FOREIGN KEY (INHALT_ID) REFERENCES INHALT (ID),
    CONSTRAINT VORLAGE_VERSION_FK_SCHEMA FOREIGN KEY (SCHEMA_ID) REFERENCES INHALT (ID),
    CONSTRAINT VORLAGE_VERSION_CK_NUMMER CHECK (HAUPT >= 1 AND NEBEN >= 0),
    CONSTRAINT VORLAGE_VERSION_CK_STATUS CHECK (STATUS IN ('DRAFT', 'FREIGEGEBEN')),
    CONSTRAINT VORLAGE_VERSION_CK_FREIGABE CHECK (
        (STATUS = 'DRAFT' AND VEROEFFENTLICHT_AB_TIME IS NULL AND VEROEFFENTLICHT_BIS_TIME IS NULL)
        OR (STATUS = 'FREIGEGEBEN' AND VEROEFFENTLICHT_AB_TIME IS NOT NULL
            AND (VEROEFFENTLICHT_BIS_TIME IS NULL OR VEROEFFENTLICHT_BIS_TIME > VEROEFFENTLICHT_AB_TIME)))
);

CREATE INDEX VORLAGE_VERSION_IX_INHALT ON VORLAGE_VERSION (INHALT_ID);
CREATE INDEX VORLAGE_VERSION_IX_SCHEMA ON VORLAGE_VERSION (SCHEMA_ID);

-- Baustein-Referenzen einer Formularversion
CREATE TABLE BAUSTEIN_REFERENZ (
    VERSION_ID          NUMBER(19) NOT NULL,
    BAUSTEIN_VORLAGE_ID NUMBER(19) NOT NULL,
    ANGABE_HAUPT        NUMBER(5)  NOT NULL,
    ANGABE_NEBEN        NUMBER(5),
    CONSTRAINT BAUSTEIN_REFERENZ_PK PRIMARY KEY (VERSION_ID, BAUSTEIN_VORLAGE_ID),
    CONSTRAINT BAUSTEIN_REFERENZ_FK_VERSION FOREIGN KEY (VERSION_ID) REFERENCES VORLAGE_VERSION (ID),
    CONSTRAINT BAUSTEIN_REFERENZ_FK_BAUSTEIN FOREIGN KEY (BAUSTEIN_VORLAGE_ID) REFERENCES VORLAGE (ID)
);

CREATE INDEX BAUSTEIN_REFERENZ_IX_BAUSTEIN ON BAUSTEIN_REFERENZ (BAUSTEIN_VORLAGE_ID);

