-- =====================================================================================
-- Vorlagenverwaltung (Querschnittsdienst Dokumentenerstellung, QD10) – Oracle
--
-- Hinweis: Versionsnummer V1 ggf. an die bestehenden Migrationen des Projekts anpassen.
-- Zeitpunkte: TIMESTAMP WITH TIME ZONE (Hibernate bildet java.time.Instant darauf ab).
-- Sequenzen: INCREMENT BY 50 passend zu allocationSize = 50 in den Entities.
-- =====================================================================================

CREATE SEQUENCE DE_KATEGORIE_SEQ START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE DE_VORLAGE_SEQ   START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE DE_VERSION_SEQ   START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE DE_INHALT_SEQ    START WITH 1 INCREMENT BY 50;

-- Kategorie (≙ Fachsystem) -------------------------------------------------------------
CREATE TABLE DE_KATEGORIE (
    ID             NUMBER(19)                   NOT NULL,
    NAME           VARCHAR2(30 CHAR)            NOT NULL,
    BESCHREIBUNG   VARCHAR2(2000 CHAR),
    ERSTELLT_AM    TIMESTAMP(6) WITH TIME ZONE  NOT NULL,
    ERSTELLT_VON   VARCHAR2(255 CHAR)           NOT NULL,
    GEAENDERT_AM   TIMESTAMP(6) WITH TIME ZONE,
    GEAENDERT_VON  VARCHAR2(255 CHAR),
    REVISION       NUMBER(19)     DEFAULT 0     NOT NULL,
    CONSTRAINT DE_KATEGORIE_PK PRIMARY KEY (ID),
    CONSTRAINT DE_KATEGORIE_UK_NAME UNIQUE (NAME)
);

-- Inhalte (ODT, PDF, XSD) – Metadaten und Daten getrennt --------------------------------
CREATE TABLE DE_INHALT (
    ID           NUMBER(19)                   NOT NULL,
    SHA256       CHAR(64 CHAR)                NOT NULL,
    FORMAT       VARCHAR2(10 CHAR)            NOT NULL,
    GROESSE      NUMBER(19)                   NOT NULL,
    ERSTELLT_AM  TIMESTAMP(6) WITH TIME ZONE  NOT NULL,
    CONSTRAINT DE_INHALT_PK PRIMARY KEY (ID),
    CONSTRAINT DE_INHALT_UK_SHA UNIQUE (SHA256, FORMAT),
    CONSTRAINT DE_INHALT_CK_FORMAT CHECK (FORMAT IN ('ODT', 'PDF', 'XSD'))
);

CREATE TABLE DE_INHALT_DATEN (
    INHALT_ID  NUMBER(19)  NOT NULL,
    DATEN      BLOB        NOT NULL,
    CONSTRAINT DE_INHALT_DATEN_PK PRIMARY KEY (INHALT_ID),
    CONSTRAINT DE_INHALT_DATEN_FK_INHALT FOREIGN KEY (INHALT_ID) REFERENCES DE_INHALT (ID)
)
LOB (DATEN) STORE AS SECUREFILE;
-- Bewusst ohne DEDUPLICATE/COMPRESS: beides erfordert die Oracle Advanced Compression Option (Lizenz).
-- Dedupliziert wird stattdessen fachlich über SHA256 in DE_INHALT.

-- Vorlage (Formular, Baustein, Merkblatt) ------------------------------------------------
CREATE TABLE DE_VORLAGE (
    ID             NUMBER(19)                   NOT NULL,
    KATEGORIE_ID   NUMBER(19)                   NOT NULL,
    NAME           VARCHAR2(100 CHAR)           NOT NULL,
    TYP            VARCHAR2(20 CHAR)            NOT NULL,
    BEZEICHNUNG    VARCHAR2(255 CHAR)           NOT NULL,
    BESCHREIBUNG   VARCHAR2(2000 CHAR),
    VEROEFF_AB     TIMESTAMP(6) WITH TIME ZONE,
    VEROEFF_BIS    TIMESTAMP(6) WITH TIME ZONE,
    ERSTELLT_AM    TIMESTAMP(6) WITH TIME ZONE  NOT NULL,
    ERSTELLT_VON   VARCHAR2(255 CHAR)           NOT NULL,
    GEAENDERT_AM   TIMESTAMP(6) WITH TIME ZONE,
    GEAENDERT_VON  VARCHAR2(255 CHAR),
    REVISION       NUMBER(19)     DEFAULT 0     NOT NULL,
    CONSTRAINT DE_VORLAGE_PK PRIMARY KEY (ID),
    CONSTRAINT DE_VORLAGE_UK_NAME UNIQUE (KATEGORIE_ID, NAME),
    CONSTRAINT DE_VORLAGE_FK_KATEGORIE FOREIGN KEY (KATEGORIE_ID) REFERENCES DE_KATEGORIE (ID),
    CONSTRAINT DE_VORLAGE_CK_TYP CHECK (TYP IN ('FORMULAR', 'BAUSTEIN', 'MERKBLATT')),
    CONSTRAINT DE_VORLAGE_CK_ZEITRAUM CHECK (VEROEFF_AB IS NULL OR VEROEFF_BIS IS NULL OR VEROEFF_BIS > VEROEFF_AB)
);

CREATE TABLE DE_VORLAGE_TAG (
    VORLAGE_ID  NUMBER(19)         NOT NULL,
    TAG         VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT DE_VORLAGE_TAG_PK PRIMARY KEY (VORLAGE_ID, TAG),
    CONSTRAINT DE_VORLAGE_TAG_FK_VORLAGE FOREIGN KEY (VORLAGE_ID) REFERENCES DE_VORLAGE (ID) ON DELETE CASCADE
);

CREATE INDEX DE_VORLAGE_TAG_IX_TAG ON DE_VORLAGE_TAG (TAG);

-- Version --------------------------------------------------------------------------------
CREATE TABLE DE_VERSION (
    ID             NUMBER(19)                   NOT NULL,
    VORLAGE_ID     NUMBER(19)                   NOT NULL,
    HAUPT          NUMBER(5)                    NOT NULL,
    NEBEN          NUMBER(5)                    NOT NULL,
    STATUS         VARCHAR2(20 CHAR)            NOT NULL,
    VEROEFF_AB     TIMESTAMP(6) WITH TIME ZONE,
    VEROEFF_BIS    TIMESTAMP(6) WITH TIME ZONE,
    KOMMENTAR      VARCHAR2(2000 CHAR),
    INHALT_ID      NUMBER(19)                   NOT NULL,
    SCHEMA_ID      NUMBER(19),
    ERSTELLT_AM    TIMESTAMP(6) WITH TIME ZONE  NOT NULL,
    ERSTELLT_VON   VARCHAR2(255 CHAR)           NOT NULL,
    GEAENDERT_AM   TIMESTAMP(6) WITH TIME ZONE,
    GEAENDERT_VON  VARCHAR2(255 CHAR),
    CONSTRAINT DE_VERSION_PK PRIMARY KEY (ID),
    CONSTRAINT DE_VERSION_UK_NUMMER UNIQUE (VORLAGE_ID, HAUPT, NEBEN),
    CONSTRAINT DE_VERSION_FK_VORLAGE FOREIGN KEY (VORLAGE_ID) REFERENCES DE_VORLAGE (ID),
    CONSTRAINT DE_VERSION_FK_INHALT FOREIGN KEY (INHALT_ID) REFERENCES DE_INHALT (ID),
    CONSTRAINT DE_VERSION_FK_SCHEMA FOREIGN KEY (SCHEMA_ID) REFERENCES DE_INHALT (ID),
    CONSTRAINT DE_VERSION_CK_NUMMER CHECK (HAUPT >= 1 AND NEBEN >= 0),
    CONSTRAINT DE_VERSION_CK_STATUS CHECK (STATUS IN ('DRAFT', 'FREIGEGEBEN')),
    -- DRAFT hat keinen Zeitraum, FREIGEGEBEN immer einen Beginn
    CONSTRAINT DE_VERSION_CK_FREIGABE CHECK (
        (STATUS = 'DRAFT' AND VEROEFF_AB IS NULL AND VEROEFF_BIS IS NULL)
     OR (STATUS = 'FREIGEGEBEN' AND VEROEFF_AB IS NOT NULL AND (VEROEFF_BIS IS NULL OR VEROEFF_BIS > VEROEFF_AB)))
);

CREATE INDEX DE_VERSION_IX_INHALT ON DE_VERSION (INHALT_ID);
CREATE INDEX DE_VERSION_IX_SCHEMA ON DE_VERSION (SCHEMA_ID);

-- Baustein-Referenzen einer Formularversion ----------------------------------------------
CREATE TABLE DE_BAUSTEIN_REF (
    VERSION_ID           NUMBER(19) NOT NULL,
    BAUSTEIN_VORLAGE_ID  NUMBER(19) NOT NULL,
    ANGABE_HAUPT         NUMBER(5)  NOT NULL,
    ANGABE_NEBEN         NUMBER(5),            -- NULL = neueste Nebenversion der Hauptversion
    CONSTRAINT DE_BAUSTEIN_REF_PK PRIMARY KEY (VERSION_ID, BAUSTEIN_VORLAGE_ID),
    CONSTRAINT DE_BAUSTEIN_REF_FK_VERSION FOREIGN KEY (VERSION_ID) REFERENCES DE_VERSION (ID) ON DELETE CASCADE,
    CONSTRAINT DE_BAUSTEIN_REF_FK_BAUSTEIN FOREIGN KEY (BAUSTEIN_VORLAGE_ID) REFERENCES DE_VORLAGE (ID)
);

-- Verwendungsnachweis: Welche Formularversionen nutzen einen Baustein?
CREATE INDEX DE_BAUSTEIN_REF_IX_BAUSTEIN ON DE_BAUSTEIN_REF (BAUSTEIN_VORLAGE_ID);
